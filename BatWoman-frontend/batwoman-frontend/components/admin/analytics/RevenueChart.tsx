"use client";

import {
    ResponsiveContainer,
    AreaChart,
    Area,
    CartesianGrid,
    Tooltip,
    XAxis,
    YAxis,
} from "recharts";

import {
    MonthlyRevenue,
} from "@/services/adminAnalytics.service";

interface RevenueChartProps {
    data: MonthlyRevenue[];
}

export default function RevenueChart({
                                         data,
                                     }: RevenueChartProps) {
    const chartData = (data ?? []).map((item) => ({
        ...item,
        revenue: item.revenue ?? 0,
    }));

    return (
        <section className="rounded-2xl border border-[#EAE3D8] bg-[#FFFDF9] p-5 shadow-[0_2px_10px_rgba(61,48,40,0.03)] sm:p-7">
            <div className="mb-6 sm:mb-8">
                <h2 className="font-[var(--font-playfair)] text-2xl text-[#3D3028] sm:text-3xl">
                    Revenue Trend
                </h2>

                <p className="mt-2 text-sm leading-6 text-[#8A7A6C]">
                    Monthly revenue generated by completed orders.
                </p>
            </div>

            <div className="h-[280px] min-w-0 sm:h-[350px] lg:h-[390px]">
                {chartData.length === 0 ? (
                    <div className="flex h-full flex-col items-center justify-center rounded-xl border border-dashed border-[#E5DCCE] bg-[#FAF7F2] text-center">
                        <p className="text-sm font-medium text-[#59483A]">
                            No revenue data available
                        </p>

                        <p className="mt-1 text-xs text-[#9A8B7B]">
                            Monthly revenue will appear here.
                        </p>
                    </div>
                ) : (
                    <ResponsiveContainer width="100%" height="100%">
                        <AreaChart
                            data={chartData}
                            margin={{
                                top: 12,
                                right: 8,
                                left: -15,
                                bottom: 0,
                            }}
                        >
                            <defs>
                                <linearGradient
                                    id="revenueGradient"
                                    x1="0"
                                    y1="0"
                                    x2="0"
                                    y2="1"
                                >
                                    <stop
                                        offset="5%"
                                        stopColor="#94764C"
                                        stopOpacity={0.3}
                                    />
                                    <stop
                                        offset="95%"
                                        stopColor="#C2A16A"
                                        stopOpacity={0.02}
                                    />
                                </linearGradient>
                            </defs>

                            <CartesianGrid
                                stroke="#EEE7DD"
                                strokeDasharray="4 5"
                                vertical={false}
                            />

                            <XAxis
                                dataKey="month"
                                tickLine={false}
                                axisLine={false}
                                tick={{
                                    fill: "#8A7A6C",
                                    fontSize: 11,
                                }}
                                tickMargin={12}
                                minTickGap={16}
                            />

                            <YAxis
                                tickLine={false}
                                axisLine={false}
                                tick={{
                                    fill: "#8A7A6C",
                                    fontSize: 11,
                                }}
                                tickFormatter={(value: number) =>
                                    value >= 100000
                                        ? `₹${(value / 100000).toFixed(1)}L`
                                        : value >= 1000
                                            ? `₹${(value / 1000).toFixed(0)}k`
                                            : `₹${value}`
                                }
                                width={55}
                            />

                            <Tooltip
                                formatter={(value) => [
                                    `₹${Number(value ?? 0).toLocaleString("en-IN")}`,
                                    "Revenue",
                                ]}
                                contentStyle={{
                                    borderRadius: "12px",
                                    border: "1px solid #EAE3D8",
                                    backgroundColor: "#FFFDF9",
                                    color: "#3D3028",
                                    boxShadow:
                                        "0 4px 16px rgba(61,48,40,0.08)",
                                }}
                                labelStyle={{
                                    color: "#8A7A6C",
                                    marginBottom: "4px",
                                }}
                            />

                            <Area
                                type="monotone"
                                dataKey="revenue"
                                stroke="#94764C"
                                strokeWidth={2.5}
                                fill="url(#revenueGradient)"
                                activeDot={{
                                    r: 5,
                                    fill: "#94764C",
                                    stroke: "#FFFDF9",
                                    strokeWidth: 2,
                                }}
                            />
                        </AreaChart>
                    </ResponsiveContainer>
                )}
            </div>
        </section>
    );
}